import 'package:flutter/material.dart';
import 'package:flutter_clean_starter/app/session/app_session.dart';
import 'package:flutter_clean_starter/core/assets/assets.gen.dart';
import 'package:flutter_clean_starter/core/extensions/context_x.dart';
import 'package:flutter_clean_starter/core/theme/tokens/app_spacing.dart';

/// Demo sign-in page used by the auth-guard example.
///
/// Signing in stores a fake token; the router then redirects back to the
/// page that was requested. Replace with a real `auth` feature.
class SignInPage extends StatelessWidget {
  /// Creates the page.
  const SignInPage({required this.session, super.key});

  /// The session to sign into.
  final AppSession session;

  @override
  Widget build(BuildContext context) {
    final l10n = context.l10n;
    return Scaffold(
      appBar: AppBar(title: Text(l10n.signInTitle)),
      body: Padding(
        padding: AppSpacing.page,
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            // Type-safe asset access generated by flutter_gen.
            Assets.icons.logo.svg(height: 64, excludeFromSemantics: true),
            AppSpacing.gapLg,
            Text(l10n.signInMessage, style: context.textTheme.bodyLarge),
            AppSpacing.gapLg,
            FilledButton(
              onPressed: () => session.signIn('demo-token'),
              child: Text(l10n.signInButton),
            ),
          ],
        ),
      ),
    );
  }
}
